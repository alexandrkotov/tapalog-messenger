/**
 * Runs after `vite build`. Two jobs:
 *
 * 1. Fills the service worker's precache list: client/public/sw.js ships with
 *    a `__PRECACHE__` placeholder; the built copy gets every file of this build
 *    plus a build hash, so a new build is a new sw.js and browsers update.
 * 2. Writes server/src/clientAssets.gen.ts — one `with { type: "file" }` import
 *    per built file and a URL-path → file map. `bun build --compile` embeds each
 *    imported file in the executable; plain `bun server/src/main.ts` reads them
 *    from client/dist. (Bun.embeddedFiles was tried first and dropped: passing
 *    built files as extra --compile entrypoints made Bun bundle the HTML and JS
 *    instead of embedding them as-is.)
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = join(import.meta.dir, "..");
const distDir = join(root, "client", "dist");
const outFile = join(root, "server", "src", "clientAssets.gen.ts");

function listFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    return entry.isDirectory() ? listFiles(full) : [full];
  });
}

const files = listFiles(distDir).sort();
if (!files.some((f) => f.endsWith(`${sep}index.html`))) {
  console.error(`No client build in ${distDir} — run the client build first.`);
  process.exit(1);
}
const urlPath = (file: string) => "/" + relative(distDir, file).split(sep).join("/");

// 1. Service worker precache list.
const swPath = join(distDir, "sw.js");
const precache = files.filter((f) => f !== swPath).map(urlPath);
const hash = createHash("sha256");
for (const f of files.filter((f) => f !== swPath)) hash.update(urlPath(f)).update(readFileSync(f));
const swSource = readFileSync(swPath, "utf-8");
if (!swSource.includes("__PRECACHE__")) {
  console.error("client/dist/sw.js has no __PRECACHE__ placeholder — was it already processed?");
  process.exit(1);
}
writeFileSync(
  swPath,
  swSource.replace("__PRECACHE__", JSON.stringify({ version: hash.digest("hex").slice(0, 12), files: ["/", ...precache] })),
);

// 2. The import map for the server.
// Each import resolves to a path string at build time; TypeScript cannot know that
// about arbitrary built files (.js, .png, …), hence the per-line ts-ignore.
const imports = files.map(
  (f, i) => `// @ts-ignore\nimport a${i} from ${JSON.stringify(relative(join(root, "server", "src"), f).split(sep).join("/"))} with { type: "file" };`,
);
const entries = files.map((f, i) => `  ${JSON.stringify(urlPath(f))}: a${i},`);
writeFileSync(
  outFile,
  // bun-types declares .html imports as HTMLBundle, but `type: "file"` makes them a path string like the rest.
  `// Generated by scripts/gen-client-assets.ts — do not edit.\n${imports.join("\n")}\n\nconst files: Record<string, unknown> = {\n${entries.join("\n")}\n};\n\nexport const assets = files as Readonly<Record<string, string>>;\n`,
);
console.log(`Embedded ${files.length} client files; service worker precaches ${precache.length + 1} URLs.`);
